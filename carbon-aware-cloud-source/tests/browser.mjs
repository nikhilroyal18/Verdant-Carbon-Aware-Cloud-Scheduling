import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
const edge = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const browser = await chromium.launch({ ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : existsSync(edge) ? { executablePath: edge } : { channel: 'chrome' }), headless: true });
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
await mkdir('test-artifacts', { recursive: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByText('Carbon emissions', { exact: true }).first().waitFor({ timeout: 90000 });
  await page.screenshot({ path: 'test-artifacts/desktop.png', fullPage: true });
  assert.equal(await page.locator('.metric-card').count(), 4);
  await page.getByRole('button', { name: 'Data centers', exact: false }).first().click();
  assert.equal(await page.locator('.center-card').count(), 4);
  await page.getByRole('button', { name: 'Add data center', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Test region');
  await page.getByLabel('Region label').fill('test-1'); await page.getByLabel('Country', { exact: true }).fill('Test country');
  await page.getByRole('button', { name: 'Save data center', exact: true }).click();
  assert.equal(await page.locator('.center-card').count(), 5);
  await page.locator('.center-card').filter({ hasText: 'Test region' }).getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert.equal(await page.locator('.center-card').count(), 4);
  await page.getByRole('button', { name: 'Scheduler', exact: true }).click();
  await page.locator('#carbonWeight').fill('80');
  await page.getByRole('button', { name: 'Save scheduler settings', exact: true }).click();
  assert.equal(await page.locator('#carbonWeight').inputValue(), '80');
  await page.getByRole('button', { name: 'Workloads', exact: true }).click();
  await page.getByLabel('Number of tasks', { exact: true }).fill('24');
  await page.getByRole('button', { name: 'Generate workloads', exact: true }).click();
  await page.getByRole('button', { name: 'Run experiment', exact: true }).click();
  await page.locator('#algorithm-filter').waitFor({ timeout: 90000 });
  await page.getByRole('button', { name: 'Run experiment', exact: true }).waitFor();
  await page.locator('#task-search').fill('TASK-0001');
  assert.equal(await page.locator('#task-table tbody tr').count(), 1);
  await page.locator('#task-table').getByRole('button', { name: 'Details for TASK-0001' }).click();
  await page.getByRole('heading', { name: 'TASK-0001' }).waitFor();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Export results', exact: true }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Strategy comparison · CSV' }).click()]);
  assert.equal(download.suggestedFilename(), 'strategy-comparison.csv');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Methodology', exact: true }).click();
  await page.getByRole('heading', { name: 'Understand the numbers.' }).waitFor();
  await page.reload(); await page.getByRole('heading', { name: 'Understand the numbers.' }).waitFor();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
  await page.screenshot({ path: 'test-artifacts/mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Mobile page overflows horizontally');
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Data centers', exact: false }).first().click();
  assert.equal(await page.locator('.sidebar.open').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: inputs, CRUD, scheduler, generation, experiment, filters, details, CSV export, persistence, mobile layout.');
} finally { await browser.close(); }
